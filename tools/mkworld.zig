//! Makes world_map.zig, the land as a flat map draws it (for choosing a
//! time zone; see src/kete_vc4/timezone_map.zig), from Natural Earth's
//! 110m Admin-0 Countries GeoJSON (as the Maps app has it): each country's
//! polygons' outer rings, their points in hundredths of a degree (east,
//! north).
//!
//!     mkworld <ne_110m_admin_0_countries.geojson> <world_map.zig>

const std = @import("std");

pub fn main(init: std.process.Init) !void {
    const arena = init.arena.allocator();
    const args = try init.minimal.args.toSlice(arena);
    if (args.len != 3) {
        std.debug.print("usage: mkworld <ne_110m.geojson> <world_map.zig>\n", .{});
        std.process.exit(2);
    }
    const cwd = std.Io.Dir.cwd();
    const geojson = try cwd.readFileAlloc(init.io, args[1], arena, .limited(32 << 20));
    const out = try generate(arena, geojson);
    const file = try cwd.createFile(init.io, args[2], .{});
    defer file.close(init.io);
    try file.writeStreamingAll(init.io, out);
}

pub fn generate(arena: std.mem.Allocator, geojson: []const u8) ![]const u8 {
    const parsed = try std.json.parseFromSliceLeaky(std.json.Value, arena, geojson, .{});
    var points: std.ArrayList([2]i16) = .empty;
    var rings: std.ArrayList([2]u32) = .empty;
    const features = parsed.object.get("features") orelse return error.NoFeatures;
    for (features.array.items) |f| {
        const geom = f.object.get("geometry") orelse continue;
        if (geom != .object) continue;
        const kind = (geom.object.get("type") orelse continue).string;
        const coords = geom.object.get("coordinates") orelse continue;
        if (std.mem.eql(u8, kind, "Polygon")) {
            try addRing(arena, coords.array.items[0], &points, &rings);
        } else if (std.mem.eql(u8, kind, "MultiPolygon")) {
            for (coords.array.items) |poly| try addRing(arena, poly.array.items[0], &points, &rings);
        }
    }
    var out: std.ArrayList(u8) = .empty;
    try out.appendSlice(arena,
        \\//! The land, for a flat map: Natural Earth's 110m countries' outer
        \\//! rings (generated by tools/mkworld.zig). Points are hundredths of a
        \\//! degree east and north; each ring is its first point and how many.
        \\
        \\
    );
    try out.print(arena, "pub const points = [{d}][2]i16{{\n", .{points.items.len});
    for (points.items) |p| try out.print(arena, "    .{{ {d}, {d} }},\n", .{ p[0], p[1] });
    try out.appendSlice(arena, "};\n\n");
    try out.print(arena, "pub const rings = [{d}][2]u32{{\n", .{rings.items.len});
    for (rings.items) |r| try out.print(arena, "    .{{ {d}, {d} }},\n", .{ r[0], r[1] });
    try out.appendSlice(arena, "};\n");
    return out.items;
}

fn addRing(a: std.mem.Allocator, ring: std.json.Value, points: *std.ArrayList([2]i16), rings: *std.ArrayList([2]u32)) !void {
    const start = points.items.len;
    for (ring.array.items) |pt| {
        const lon = number(pt.array.items[0]);
        const lat = number(pt.array.items[1]);
        try points.append(a, .{ @intFromFloat(@round(lon * 100)), @intFromFloat(@round(lat * 100)) });
    }
    if (points.items.len - start >= 3) try rings.append(a, .{ @intCast(start), @intCast(points.items.len - start) }) else points.shrinkRetainingCapacity(start);
}

fn number(v: std.json.Value) f64 {
    return switch (v) {
        .float => |f| f,
        .integer => |i| @floatFromInt(i),
        else => 0,
    };
}

test "a polygon's outer ring, and a multipolygon's" {
    var arena: std.heap.ArenaAllocator = .init(std.testing.allocator);
    defer arena.deinit();
    const out = try generate(arena.allocator(),
        \\{"type": "FeatureCollection", "features": [
        \\ {"type": "Feature", "geometry": {"type": "Polygon", "coordinates": [[[0, 0], [10.5, 0], [10.5, 20], [0, 0]], [[1, 1], [2, 1], [2, 2], [1, 1]]]}},
        \\ {"type": "Feature", "geometry": {"type": "MultiPolygon", "coordinates": [[[[-5, -5], [-4, -5], [-4, -4], [-5, -5]]]]}}]}
    );
    try std.testing.expect(std.mem.indexOf(u8, out, "pub const points = [8][2]i16") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, ".{ 1050, 2000 }") != null);
    try std.testing.expect(std.mem.indexOf(u8, out, "pub const rings = [2][2]u32") != null);
}
